#!/usr/bin/env python3
"""Generate the diagnostics reference page from the error-code registry (CT-5).

Plan §6 M3.3 / §5.2 CT-5: "errors/*.toml (code, category, summary, long
explanation, example fixtures) generates the ErrorCode enum, `glyim --explain
E0123`, the docs page, and the ledger's per-feature errors cross-check."

The registry (`crates/glyim-diag/errors/codes.toml`) is the source of truth;
this script renders it as `docs/reference/diagnostics.md`. The committed page
is verified by `--check` (exit 1 on drift) wired into `just verify` and CI's
lint job, the same contract `glyim-ledger render-gaps --check` enforces for
KNOWN_GAPS.md.

The display letters mirror `ErrorCategory::as_letter` in
`crates/glyim-diag/src/lib.rs` (Lex=E, Parse=P, NameResolution=N, Type=T,
Lifetime=L, Borrow=B, Comptime=C, Io=I, Internal=X); if that mapping changes,
update both places in the same commit — the CLI's own list-mode test pins the
letters against the Rust side.
"""

from __future__ import annotations

import argparse
import sys
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
CODES_TOML = REPO / "crates" / "glyim-diag" / "errors" / "codes.toml"
OUT_PATH = REPO / "docs" / "reference" / "diagnostics.md"

# Mirrors ErrorCategory::as_letter (crates/glyim-diag/src/lib.rs).
CATEGORY_LETTERS = {
    "Lex": "E",
    "Parse": "P",
    "NameResolution": "N",
    "Type": "T",
    "Lifetime": "L",
    "Borrow": "B",
    "Comptime": "C",
    "Io": "I",
    "Internal": "X",
}

CATEGORY_BLURBS = {
    "Lex": "Lexing — the lexer could not tokenize the input.",
    "Parse": "Parsing — the parser did not expect this token.",
    "NameResolution": "Name resolution — an item or path did not resolve.",
    "Type": "Type checking — types disagreed with their use.",
    "Lifetime": "Lifetimes — region constraints were unsatisfiable.",
    "Borrow": "Borrow checking — the NLL borrow checker rejected the code.",
    "Comptime": "Compile-time evaluation — a const/compile-time step failed.",
    "Io": "I/O — a file or process interaction failed.",
    "Internal": "Internal — a compiler-side invariant or setup failure.",
}


def render(codes: list[dict]) -> str:
    lines: list[str] = []
    lines.append("<!-- generated by `scripts/gen-diagnostics-docs.py`; DO NOT EDIT -->")
    lines.append("<!-- Source of truth: `crates/glyim-diag/errors/codes.toml` (plan §6 M3.3, CT-5). -->")
    lines.append("<!-- `--check` mode fails on any drift, like `glyim-ledger render-gaps --check`. -->")
    lines.append("")
    lines.append("# Diagnostics reference")
    lines.append("")
    lines.append(
        f"Every diagnostic code the Glyim compiler can emit, {len(codes)} registered in "
        "`crates/glyim-diag/errors/codes.toml`. The compiler driver explains one at "
        "the terminal with `glyim --explain <CODE>` (for example "
        "`glyim --explain T0060`); a bare `glyim --explain` lists every code."
    )
    lines.append("")
    current_category = None
    for code in codes:
        category = code["category"]
        letter = CATEGORY_LETTERS[category]
        number = code["number"]
        display = f"{letter}{number:04d}"
        if category != current_category:
            current_category = category
            lines.append(f"## {category} ({letter}0000–{letter}9999)")
            lines.append("")
            lines.append(CATEGORY_BLURBS[category])
            lines.append("")
        lines.append(f"### {display} — {code['title']}")
        lines.append("")
        lines.append(code["explanation"])
        lines.append("")
    return "\n".join(lines)


def load_codes() -> list[dict]:
    with CODES_TOML.open("rb") as f:
        root = tomllib.load(f)
    codes = root.get("code")
    if not isinstance(codes, list) or not codes:
        raise SystemExit(f"{CODES_TOML}: must contain a non-empty [[code]] table array")
    seen: set[str] = set()
    ordered: list[dict] = []
    for entry in codes:
        for field in ("category", "number", "title", "explanation"):
            if field not in entry:
                raise SystemExit(f"{CODES_TOML}: [[code]] entry missing `{field}`")
        category = entry["category"]
        if category not in CATEGORY_LETTERS:
            raise SystemExit(
                f"{CODES_TOML}: unknown category `{category}` "
                f"(update CATEGORY_LETTERS together with ErrorCategory::as_letter)"
            )
        display = f"{CATEGORY_LETTERS[category]}{entry['number']:04d}"
        if display in seen:
            raise SystemExit(f"{CODES_TOML}: duplicate code {display}")
        seen.add(display)
        ordered.append(entry)
    # The Rust registry asserts (category, number) sort order (plan §3.5);
    # mirror that so the page never reorders silently.
    keys = [
        (list(CATEGORY_LETTERS).index(c["category"]), c["number"]) for c in ordered
    ]
    if keys != sorted(keys):
        raise SystemExit(
            f"{CODES_TOML}: entries must be sorted by (category, number); "
            "the Rust registry asserts the same order"
        )
    return ordered


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail with exit 1 when the committed page differs from the registry",
    )
    args = parser.parse_args()

    rendered = render(load_codes())
    if args.check:
        if not OUT_PATH.exists():
            print(f"error: {OUT_PATH} is missing; run `python3 scripts/gen-diagnostics-docs.py`", file=sys.stderr)
            return 1
        committed = OUT_PATH.read_text(encoding="utf-8")
        if committed != rendered:
            print(
                f"error: {OUT_PATH} disagrees with {CODES_TOML}; "
                "run `python3 scripts/gen-diagnostics-docs.py` and commit the result",
                file=sys.stderr,
            )
            return 1
        print(f"diagnostics reference up to date ({OUT_PATH})")
        return 0
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUT_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
