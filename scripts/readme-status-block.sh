#!/usr/bin/env bash
# README generated status block (plan M0.3 "README status section gets
# generated-content markers" + M1.9 "README block" renderer remainder).
#
# The block is DERIVED data: it mirrors the generated summary of the
# committed `STATUS.md` (itself produced by `glyim-ledger status`) into the
# README between explicit `ledger:status` markers. No human-typed status
# prose — constitution C1: status is computed, never typed.
#
# Usage:
#   scripts/readme-status-block.sh           # rewrite the README block in place
#   scripts/readme-status-block.sh --check   # exit 1 when the block drifted
#
# The composed block carries the readiness headline and the level
# histogram (not the 254-row per-feature table — that lives in STATUS.md
# and STATUS.json).
set -euo pipefail
cd "$(dirname "$0")/.."

START='<!-- ledger:status:start (generated by `glyim-ledger status`; DO NOT EDIT) -->'
END='<!-- ledger:status:end -->'
README='README.md'
STATUS='STATUS.md'

compose_block() {
    # STATUS.md's generated content sits between its own markers; the
    # README mirror keeps everything up to (excluding) the per-feature
    # table header.
    awk -v start="$START" -v end="$END" '
        index($0, start) { inblock = 1; next }
        index($0, end) { inblock = 0; next }
        inblock && /^\| Feature \|/ { exit }
        inblock { print }
    ' "$STATUS"
}

readme_block() {
    awk -v start="$START" -v end="$END" '
        index($0, start) { inblock = 1; print; next }
        index($0, end) { inblock = 0; print; next }
        inblock { print }
    ' "$README"
}

compose_readme() {
    # Compose the full README: everything up to the start marker, the
    # regenerated block, everything from the end marker on.
    block="$(compose_block)"
    awk -v start="$START" -v end="$END" -v block="$block" '
        BEGIN { inblock = 0; printed = 0; n = split(block, lines, "\n") }
        index($0, start) {
            inblock = 1; print
            for (i = 1; i <= n; i++) print lines[i]
            next
        }
        index($0, end) { inblock = 0; print; printed = 1; next }
        inblock { next }
        { print }
    ' "$README"
}

if [ "${1:-}" = "--check" ]; then
    # The gate must be honest about its own presence: a README without
    # the markers carries hand-typed status prose (constitution C1 —
    # status is computed, never typed), and compose_readme would compare
    # the file against itself. Fail loudly instead of passing vacuously.
    if ! grep -qF "$START" "$README" || ! grep -qF "$END" "$README"; then
        echo "README carries no $START/$END markers: the generated status block (plan M1.9) is missing (embed it with: scripts/readme-status-block.sh)" >&2
        exit 1
    fi
    composed="$(compose_readme)"
    committed="$(cat "$README")"
    if [ "$composed" != "$committed" ]; then
        echo "README status block drifted from STATUS.md (regenerate with: scripts/readme-status-block.sh)" >&2
        diff -u <(printf '%s\n' "$committed") <(printf '%s\n' "$composed") | head -30 >&2 || true
        exit 1
    fi
    echo "README status block OK (matches STATUS.md)"
    exit 0
fi

compose_readme > "$README.tmp"
mv "$README.tmp" "$README"
echo "wrote the README status block from STATUS.md"
