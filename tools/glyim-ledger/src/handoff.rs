/// The `glyim.ledger-handoff/1` JSON document (the serialization-only
/// re-shape of [`HandoffOutcome`]: the date as a `YYYY-MM-DD` string, the
/// gate as an explicit `ok` field — the `WaiversDocument` split).
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct HandoffDocument {
    /// Schema tag, always [`HANDOFF_SCHEMA`].
    pub schema: &'static str,
    /// The assessment date (`YYYY-MM-DD`).
    pub today: String,
    /// Feature entries the compute engine loaded.
    pub features: usize,
    /// Evidence records that entered the computation.
    pub records: usize,
    /// The L0–L5 level histogram.
    pub levels: HandoffLevels,
    /// Full (unfiltered) queue length before the top-N slice.
    pub queue_total: usize,
    /// The rendered work-queue slice, queue order (rank-sorted).
    pub items: Vec<HandoffItem>,
    /// Open gaps with no reproducible witness.
    pub witness_debt: Vec<String>,
    /// Waivers inside their horizon.
    pub waivers_valid: usize,
    /// Waivers past their horizon (C9 debt).
    pub waivers_expired: usize,
    /// The soonest still-valid expiry, or `None`.
    pub next_expiring: Option<HandoffExpiry>,
    /// Error-severity diagnostics across the composed faces.
    pub error_diagnostics: usize,
    /// Whether the handoff gate passed ([`HandoffOutcome::is_ok`]).
    pub ok: bool,
}

/// Renders a [`HandoffOutcome`] into one of the two handoff faces.
///
/// The seam that keeps both renderers interchangeable for consumers:
/// tests and benches drive them through this trait exactly like the
/// `WaiversRenderer` and `KnownGapsRenderer` seams.
pub trait HandoffRenderer {
    /// Renders the face (complete bytes, including trailing newline).
    fn render(&self, outcome: &HandoffOutcome) -> String;
}

/// The marker-delimited Markdown handoff document (the `HANDOFF.md`
/// face — short by contract: histogram, top-N queue, waiver health,
/// witness debt).
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct TextHandoffRenderer;

impl HandoffRenderer for TextHandoffRenderer {
    fn render(&self, outcome: &HandoffOutcome) -> String {
        let mut text = String::new();
        let _ = writeln!(text, "{HANDOFF_MD_START}");
        let _ = writeln!(text, "# Session handoff — {}", outcome.today.to_iso());
        let _ = writeln!(text);
        let _ = writeln!(text, "## Readiness");
        let _ = writeln!(
            text,
            "- features {}, evidence records {}",
            outcome.features, outcome.records
        );
        let _ = writeln!(
            text,
            "- computed levels: L0 {}, L1 {}, L2 {}, L3 {}, L4 {}, L5 {} \
             (unmeasured hardening)",
            outcome.levels.l0,
            outcome.levels.l1,
            outcome.levels.l2,
            outcome.levels.l3,
            outcome.levels.l4,
            outcome.levels.l5,
        );
        let _ = writeln!(text, "- error diagnostics {}", outcome.error_diagnostics);
        let _ = writeln!(text);
        let _ = writeln!(
            text,
            "## Work queue (top {} of {})",
            outcome.items.len(),
            outcome.queue_total
        );
        for item in &outcome.items {
            let lane = item.lane.as_deref().map_or("-".to_string(), String::from);
            let _ = writeln!(
                text,
                "{}. [{}] {} — {}",
                item.rank, lane, item.id, item.title
            );
        }
        let _ = writeln!(text);
        let _ = writeln!(text, "## Waivers (constitution C9)");
        let _ = writeln!(
            text,
            "- valid {}, expired {}",
            outcome.waivers_valid, outcome.waivers_expired
        );
        match &outcome.next_expiring {
            Some(expiry) => {
                let _ = writeln!(text, "- next expiring: {} on {}", expiry.id, expiry.expires);
            }
            None => {
                let _ = writeln!(text, "- none in flight");
            }
        }
        let _ = writeln!(text);
        let _ = writeln!(text, "## Witness debt");
        if outcome.witness_debt.is_empty() {
            let _ = writeln!(text, "- none");
        } else {
            for id in &outcome.witness_debt {
                let _ = writeln!(text, "- {id}");
            }
        }
        let _ = writeln!(text, "{HANDOFF_MD_END}");
        text
    }
}

/// The `glyim.ledger-handoff/1` JSON face.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct JsonHandoffRenderer;

impl HandoffRenderer for JsonHandoffRenderer {
    fn render(&self, outcome: &HandoffOutcome) -> String {
        let document = HandoffDocument {
            schema: HANDOFF_SCHEMA,
            today: outcome.today.to_iso(),
            features: outcome.features,
            records: outcome.records,
            levels: outcome.levels,
            queue_total: outcome.queue_total,
            items: outcome.items.clone(),
            witness_debt: outcome.witness_debt.clone(),
            waivers_valid: outcome.waivers_valid,
            waivers_expired: outcome.waivers_expired,
            next_expiring: outcome.next_expiring.clone(),
            error_diagnostics: outcome.error_diagnostics,
            ok: outcome.is_ok(),
        };
        let mut text = serde_json::to_string_pretty(&document)
            .expect("the glyim.ledger-handoff/1 document is a serialisation-only struct");
        text.push('\n');
        text
    }
}

/// Renders the Markdown handoff document (the [`TextHandoffRenderer`]
/// face).
#[must_use]
pub fn format_handoff_text(outcome: &HandoffOutcome) -> String {
    TextHandoffRenderer.render(outcome)
}

/// Renders the `glyim.ledger-handoff/1` JSON contract (the
/// [`JsonHandoffRenderer`] face).
#[must_use]
pub fn format_handoff_json(outcome: &HandoffOutcome) -> String {
    JsonHandoffRenderer.render(outcome)
}

// -- run faces ---------------------------------------------------------------

/// Runs a full `ledger handoff` pass: the composed state from `source`
/// (the CLI wires [`FileHandoffSource`]; tests and in-process consumers
/// wire [`InMemoryHandoffSource`]) rendered through the engine.
#[must_use]
pub fn run_handoff(root: &Path, source: &dyn HandoffSource, items: usize) -> HandoffOutcome {
    let span = tracing::info_span!(
        "handoff",
        root = %root.display(),
        items = items,
    );
    let _enter = span.enter();
    let state = source.load(root);
    let outcome = render_handoff(&state, items);
    tracing::debug!(
        features = outcome.features,
        queue_total = outcome.queue_total,
        items = outcome.items.len(),
        witness_debt = outcome.witness_debt.len(),
        "handoff composed"
    );
    outcome
}

/// Result of the write/check face of `ledger handoff` (the
/// `StatusRendered` shape).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HandoffRendered {
    /// The underlying engine outcome.
    pub outcome: HandoffOutcome,
    /// The face that was rendered.
    pub format: HandoffFormat,
    /// The rendered bytes (with trailing newline).
    pub rendered: String,
    /// The file the render was written to or checked against; `None` when
    /// the caller asked for stdout.
    pub target: Option<PathBuf>,
    /// Whether `--check` byte-compared instead of writing.
    pub checked: bool,
}

/// Renders the handoff for `root` and either writes it to `out` (default
/// `HANDOFF.md` / `HANDOFF.json` by face, under `root`, when `check`) or
/// — with `check` — byte-compares it against the committed file and fails
/// on any drift.
///
/// # Errors
///
/// [`LedgerCliError::HandoffDrift`] when `--check` cannot read the
/// committed document or the committed bytes differ from the render;
/// [`LedgerCliError::HandoffWrite`] when the requested document cannot be
/// written. Composed-face diagnostics travel in
/// [`HandoffRendered::outcome`] and fail the exit code like every other
/// pipeline (the debt is displayed, not silent).
pub fn run_handoff_out(
    root: &Path,
    source: &dyn HandoffSource,
    items: usize,
    format: HandoffFormat,
    out: Option<&Path>,
    check: bool,
) -> Result<HandoffRendered, LedgerCliError> {
    let span = tracing::info_span!(
        "handoff_out",
        root = %root.display(),
        format = format.as_str(),
        check = check,
    );
    let _enter = span.enter();

    let outcome = run_handoff(root, source, items);
    let rendered = match format {
        HandoffFormat::Markdown => format_handoff_text(&outcome),
        HandoffFormat::Json => format_handoff_json(&outcome),
    };

    let target = out.map(Path::to_path_buf);
    if check {
        let target = target.unwrap_or_else(|| {
            root.join(match format {
                HandoffFormat::Markdown => HANDOFF_MD_TARGET,
                HandoffFormat::Json => HANDOFF_JSON_TARGET,
            })
        });
        let committed =
            std::fs::read_to_string(&target).map_err(|err| LedgerCliError::HandoffDrift {
                path: target.display().to_string(),
                detail: format!("cannot read the committed document: {err}"),
            })?;
        if committed != rendered {
            return Err(LedgerCliError::HandoffDrift {
                path: target.display().to_string(),
                detail: format!(
                    "the committed document drifted from the composed state \
                     (committed {} bytes, render {} bytes)",
                    committed.len(),
                    rendered.len(),
                ),
            });
        }
        return Ok(HandoffRendered {
            outcome,
            format,
            rendered,
            target: Some(target),
            checked: true,
        });
    }
    if let Some(target) = &target {
        std::fs::write(target, &rendered).map_err(|err| LedgerCliError::HandoffWrite {
            path: target.display().to_string(),
            detail: err.to_string(),
        })?;
    }
    Ok(HandoffRendered {
        outcome,
        format,
        rendered,
        target,
        checked: false,
    })
}

