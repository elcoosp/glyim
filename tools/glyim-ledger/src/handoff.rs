//! `ledger handoff` — the plan §3.7 session-handoff generator.
//!
//! The plan's CLI table names a `ledger handoff` face: "Generates the
//! (short) session handoff from state — replaces hand-written
//! `HANDOFF.md`". Every input the document needs already exists as a
//! deterministic face output — the M1.8 level engine ([`ComputeOutcome`]),
//! the §3.9 work queue ([`NextOutcome`]), and the C9 waiver-health report
//! ([`WaiversOutcome`]) — but composing them meant running four commands
//! and merging them by hand. This face composes them once, as a pure
//! function, into one short document an operator or agent reads at the
//! start of a session:
//!
//! - **Readiness** — feature count, evidence records, the L0–L5 level
//!   histogram, and the error-diagnostic count,
//! - **Work queue** — the top-N ranked items (the full queue stays one
//!   `next` call away; the handoff stays short),
//! - **Waivers (C9)** — valid vs. expired counts and the next expiring
//!   waiver (an expired exception fails the handoff gate exactly as it
//!   fails the health face),
//! - **Witness debt** — the open gaps with no reproducible witness.
//!
//! # The seams
//!
//! [`HandoffSource`] decouples the composition engine from where the
//! three face outcomes come from — the same File/InMemory twin pattern
//! [`crate::waivers`] establishes for [`crate::WaiverSource`]:
//! [`FileHandoffSource`] runs the real faces over the registry under
//! `ROOT`, [`InMemoryHandoffSource`] hands the engine a pre-built state
//! for tests and in-process consumers. New sources (a cached state, a CI
//! artifact) plug in as one more [`HandoffSource`] impl, never as outcome
//! fields. [`HandoffRenderer`] mirrors [`crate::WaiversRenderer`]: the
//! Markdown document face (marker-delimited, `HANDOFF.md`-shaped) and the
//! `glyim.ledger-handoff/1` JSON contract render from one
//! [`HandoffOutcome`].
//!
//! # Determinism (plan C1/M1.13)
//!
//! The engine is a pure function of the state: the queue slice sorts by
//! rank before the top-N selection (input order never leaks into the
//! render), witness debt follows queue order (already a total order),
//! and `today` is pinned by the waivers outcome rather than consulted
//! again. Both renderers run twice, byte-identical, pinned by golden and
//! round-trip tests.
//!
//! # Gate semantics
//!
//! [`HandoffOutcome::is_ok`] is the face's exit-code contract: zero
//! error-severity diagnostics across the three composed faces **and** no
//! expired waiver (constitution C9: an expired exception fails CI even
//! when no regression needs covering). The debt is rendered, never
//! silent — a red handoff is still a complete handoff.
//!
//! This module also carries the write/check face
//! ([`run_handoff_out`]): `--out PATH` writes the rendered document
//! (default `HANDOFF.md` / `HANDOFF.json` by face, under ROOT) and
//! `--check` byte-compares the committed document against the render —
//! the exact drift-gate contract [`crate::run_status_out`] established
//! for `STATUS.md`.

