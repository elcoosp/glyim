    #[test]
    fn parse_args_rejects_bad_handoff_flags() {
        for args in [
            &["handoff", "--items", "x"][..],
            &["handoff", "--items", "0"][..],
            &["handoff", "--items", "21"][..],
        ] {
            let err = parse_args(args.iter().map(|s| s.to_string())).expect_err("bad --items");
            assert!(
                matches!(err, LedgerCliError::HandoffBadItems { .. }),
                "--items {args:?} must fail with HandoffBadItems"
            );
        }
        let err = parse_args(
            ["handoff", "--format", "yaml"]
                .iter()
                .map(|s| s.to_string()),
        )
        .expect_err("bad format");
        assert!(matches!(err, LedgerCliError::HandoffBadFormat { .. }));
        let err = parse_args(["handoff", "--items"].iter().map(|s| s.to_string()))
            .expect_err("missing value");
        assert!(matches!(err, LedgerCliError::HandoffMissingValue { .. }));
        let err = parse_args(["handoff", "--unknown"].iter().map(|s| s.to_string()))
            .expect_err("unknown flag");
        assert!(matches!(err, LedgerCliError::UnknownFlag { .. }));
        let err = parse_args(["handoff", "a", "b"].iter().map(|s| s.to_string()))
            .expect_err("two positional roots");
        assert!(matches!(err, LedgerCliError::ExtraArgument { .. }));
    }

