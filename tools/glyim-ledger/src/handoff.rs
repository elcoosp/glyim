/// Schema tag of the handoff JSON contract (pinned by the round-trip
/// test; bump the minor when adding fields, the major when changing or
/// removing them).
pub const HANDOFF_SCHEMA: &str = "glyim.ledger-handoff/1";

/// Marker that opens the generated Markdown block (the STATUS.md
/// convention: generated content is delimited so embedded updates never
/// eat hand-written text).
pub const HANDOFF_MD_START: &str =
    "<!-- ledger:handoff:start (generated by `glyim-ledger handoff`; DO NOT EDIT) -->";

/// Marker that closes the generated Markdown block.
pub const HANDOFF_MD_END: &str = "<!-- ledger:handoff:end -->";

/// Committed-file default for the Markdown face (`handoff --check`).
pub const HANDOFF_MD_TARGET: &str = "HANDOFF.md";

/// Committed-file default for the JSON face (`handoff --check --format
/// json`).
pub const HANDOFF_JSON_TARGET: &str = "HANDOFF.json";

/// Default number of work-queue items the face renders (the plan wants
/// the handoff *short*; the full queue is one `next` call away).
pub const HANDOFF_DEFAULT_ITEMS: usize = 5;

/// Upper bound for `--items` (the handoff is a summary, not the queue).
pub const HANDOFF_MAX_ITEMS: usize = 20;

/// Output format of the `handoff` subcommand.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum HandoffFormat {
    /// The marker-delimited Markdown document (default; `HANDOFF.md`-shaped).
    Markdown,
    /// The `glyim.ledger-handoff/1` JSON contract.
    Json,
}

impl HandoffFormat {
    /// The `--format` wire spelling.
    #[must_use]
    pub fn as_str(self) -> &'static str {
        match self {
            HandoffFormat::Markdown => "md",
            HandoffFormat::Json => "json",
        }
    }
}

/// The composed face outcomes the engine renders. Loaded by a
/// [`HandoffSource`], consumed by [`render_handoff`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HandoffState {
    /// The M1.8 level-computation outcome.
    pub compute: ComputeOutcome,
    /// The §3.9 ranked work queue (unfiltered; the engine slices).
    pub next: NextOutcome,
    /// The C9 waiver-health outcome (pins the assessment date).
    pub waivers: WaiversOutcome,
}

/// Source of the composed state for the handoff engine.
///
/// The seam that keeps [`render_handoff`] independent of where its three
/// face outcomes come from: the two implementations below cover the live
/// registry and in-process fixtures, and future sources (a cached state,
/// a CI artifact) plug in as one more impl without the engine changing
/// shape.
pub trait HandoffSource {
    /// Loads the composed state for the registry under `root`.
    fn load(&self, root: &Path) -> HandoffState;
}

/// Runs the real faces over the registry under `root`: the M1.8 compute
/// engine, the §3.9 work queue, and the C9 waiver health (through the
/// same [`FileWaiverSource`] the `waivers` face and the `diff` gate use,
/// so a handoff can never disagree with them about
/// `ledger/waivers.toml`).
pub struct FileHandoffSource;

impl HandoffSource for FileHandoffSource {
    fn load(&self, root: &Path) -> HandoffState {
        HandoffState {
            compute: run_compute(root, None),
            next: run_next(root),
            waivers: run_waivers(root, &FileWaiverSource),
        }
    }
}

/// Hands the engine a pre-built state (tests and in-process consumers).
#[derive(Debug, Clone)]
pub struct InMemoryHandoffSource {
    /// The state every `load` returns (cloned).
    pub state: HandoffState,
}

impl HandoffSource for InMemoryHandoffSource {
    fn load(&self, _root: &Path) -> HandoffState {
        self.state.clone()
    }
}

/// One rendered work-queue row of the handoff (the top-N slice of the
/// §3.9 queue, reduced to the fields a session handoff needs).
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct HandoffItem {
    /// 1-based position in the full queue (preserved from [`crate::next`]
    /// so a sliced handoff still shows honest, non-contiguous ranks).
    pub rank: usize,
    /// Registry ID (`GAP-NNNN` or a feature ID).
    pub id: String,
    /// Human-readable entry title.
    pub title: String,
    /// Suggested owner lane letter, or `None` when unresolvable.
    pub lane: Option<String>,
    /// Deterministic one-line reason the item is queued.
    pub why: String,
}

/// The next waiver expiry the operator should watch (the soonest
/// still-valid expiry, or `None` when no valid waiver exists).
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct HandoffExpiry {
    /// The waiver ID.
    pub id: String,
    /// The `YYYY-MM-DD` expiry date (echoed verbatim).
    pub expires: String,
}

/// Per-level feature counts in the JSON contract (the STATUS.md
/// histogram shape).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
pub struct HandoffLevels {
    /// Features computed at L0 (declared only).
    #[serde(rename = "L0")]
    pub l0: usize,
    /// Features computed at L1 (parses).
    #[serde(rename = "L1")]
    pub l1: usize,
    /// Features computed at L2 (checks).
    #[serde(rename = "L2")]
    pub l2: usize,
    /// Features computed at L3 (interpreted).
    #[serde(rename = "L3")]
    pub l3: usize,
    /// Features computed at L4 (native-verified).
    #[serde(rename = "L4")]
    pub l4: usize,
    /// Features computed at L5 (hardened; unreachable today — see the
    /// compute module's unmeasured hardening axes).
    #[serde(rename = "L5")]
    pub l5: usize,
}

/// Result of a full `ledger handoff` run: the composed summary both
/// renderers consume. The JSON face re-shapes this into
/// [`HandoffDocument`] (the `WaiversDocument` split: dates as
/// `YYYY-MM-DD` strings, the gate as an explicit `ok` field).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HandoffOutcome {
    /// The JSON contract tag (echoed for machine consumers).
    pub schema: &'static str,
    /// The date the assessment ran against (pinned by the waivers
    /// outcome; no second clock consult).
    pub today: NaiveDate,
    /// Feature entries the compute engine loaded.
    pub features: usize,
    /// Evidence records that entered the computation.
    pub records: usize,
    /// The L0–L5 level histogram.
    pub levels: HandoffLevels,
    /// Full (unfiltered) queue length before the top-N slice.
    pub queue_total: usize,
    /// The rendered work-queue slice, queue order (rank-sorted).
    pub items: Vec<HandoffItem>,
    /// Open gaps with no reproducible witness (queue order; the
    /// registry's witness debt rendered, not failed).
    pub witness_debt: Vec<String>,
    /// Waivers inside their horizon.
    pub waivers_valid: usize,
    /// Waivers past their horizon (C9 debt; fails the gate).
    pub waivers_expired: usize,
    /// The soonest still-valid expiry, or `None` without valid waivers.
    pub next_expiring: Option<HandoffExpiry>,
    /// Error-severity diagnostics across the three composed faces,
    /// sorted-source order summed (the count drives the gate).
    pub error_diagnostics: usize,
}

impl HandoffOutcome {
    /// True when the handoff gate passes: zero error-severity
    /// diagnostics across the composed faces and no expired waiver (the
    /// C9 contract).
    #[must_use]
    pub fn is_ok(&self) -> bool {
        self.error_diagnostics == 0 && self.waivers_expired == 0
    }
}

// -- engine ------------------------------------------------------------------

/// Composes the state into the short session handoff: a pure function
/// with no clock, no filesystem, and no environment — the assessment
/// date rides in on the waivers outcome, the queue slice sorts by rank
/// before the top-N selection (input order never leaks into the render),
/// and witness debt follows queue order (already a total order from the
/// §3.9 comparator).
#[must_use]
pub fn render_handoff(state: &HandoffState, items: usize) -> HandoffOutcome {
    // Rank-sort defensively: the §3.9 engine emits the queue sorted, but
    // the handoff contract must not depend on that upstream courtesy.
    let mut ranked = state.next.queue.clone();
    ranked.sort_by_key(|item| item.rank);

    let mut levels = HandoffLevels {
        l0: 0,
        l1: 0,
        l2: 0,
        l3: 0,
        l4: 0,
        l5: 0,
    };
    for entry in &state.compute.entries {
        match entry.computed_level {
            ledger_schema::Level::L0 => levels.l0 += 1,
            ledger_schema::Level::L1 => levels.l1 += 1,
            ledger_schema::Level::L2 => levels.l2 += 1,
            ledger_schema::Level::L3 => levels.l3 += 1,
            ledger_schema::Level::L4 => levels.l4 += 1,
            ledger_schema::Level::L5 => levels.l5 += 1,
        }
    }

    let slice: Vec<HandoffItem> = ranked
        .iter()
        .take(items)
        .map(|item| HandoffItem {
            rank: item.rank,
            id: item.id.clone(),
            title: item.title.clone(),
            lane: item.lane.map(|lane| lane.as_str().to_string()),
            why: item.why.clone(),
        })
        .collect();

    let witness_debt: Vec<String> = ranked
        .iter()
        .filter(|item| {
            matches!(
                item.kind,
                crate::next::WorkKind::Gap {
                    witnessed: false,
                    ..
                }
            )
        })
        .map(|item| item.id.clone())
        .collect();

    // The next expiry the operator should watch: the soonest still-valid
    // waiver (expired rows are debt, not upcoming deadlines), date first
    // then ID for a total order.
    let next_expiring = state
        .waivers
        .rows
        .iter()
        .filter(|row| row.verdict == crate::waivers::WaiverVerdict::Valid)
        .min_by(|a, b| a.expires.cmp(&b.expires).then(a.id.cmp(&b.id)))
        .map(|row| HandoffExpiry {
            id: row.id.clone(),
            expires: row.expires.clone(),
        });

    let error_diagnostics = error_count(&state.compute.diagnostics)
        + error_count(&state.next.diagnostics)
        + error_count(&state.waivers.diagnostics);

    HandoffOutcome {
        schema: HANDOFF_SCHEMA,
        today: state.waivers.today,
        features: state.compute.features,
        records: state.compute.records,
        levels,
        queue_total: ranked.len(),
        items: slice,
        witness_debt,
        waivers_valid: state.waivers.valid,
        waivers_expired: state.waivers.expired,
        next_expiring,
        error_diagnostics,
    }
}

/// Counts the error-severity diagnostics of one composed face (the
/// engine only *sums* severities; the prose stays with the renderers).
fn error_count(diagnostics: &[ledger_schema::Diagnostic]) -> usize {
    diagnostics
        .iter()
        .filter(|diagnostic| diagnostic.severity == Severity::Error)
        .count()
}

