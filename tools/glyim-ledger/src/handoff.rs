    #[test]
    fn expired_waivers_and_error_diagnostics_fail_the_gate() {
        let expired = render_handoff(&state(), 2);
        assert!(!expired.is_ok(), "an expired waiver fails the C9 gate");
        assert_eq!(expired.error_diagnostics, 0);

        let mut errored = state();
        errored.waivers.rows.clear();
        errored.waivers.expired = 0;
        errored.waivers.valid = 0;
        errored.waivers.waivers = 0;
        errored.compute.diagnostics = vec![ledger_schema::Diagnostic {
            code: "LEDGER-SCHEMA",
            message: "synthetic load failure".to_string(),
            severity: ledger_schema::Severity::Error,
        }];
        let outcome = render_handoff(&errored, 2);
        assert_eq!(outcome.error_diagnostics, 1);
        assert!(!outcome.is_ok(), "an error diagnostic fails the gate");

        let mut warned = state();
        warned.waivers.rows.clear();
        warned.waivers.expired = 0;
        warned.waivers.valid = 0;
        warned.waivers.waivers = 0;
        warned.compute.diagnostics = vec![ledger_schema::Diagnostic {
            code: "LEDGER-WARN",
            message: "synthetic warning".to_string(),
            severity: ledger_schema::Severity::Warning,
        }];
        assert!(
            render_handoff(&warned, 2).is_ok(),
            "warnings display, not fail"
        );
    }

