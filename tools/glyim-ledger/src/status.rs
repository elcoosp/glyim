//! `ledger status` — the M1.9 status renderers (plan §6 M1.9, first slice).
//!
//! Plan M1.9 renders computed status for humans and machines: this slice
//! adds the two artifacts that hang directly off the M1.8 engine —
//!
//! - [`format_status_json`]: the `glyim.status/1` contract — per-level
//!   histogram plus the per-feature summary entries (no `missing`-reason
//!   prose; the compute contract carries that),
//! - [`format_status_markdown`]: the deterministic, marker-delimited
//!   Markdown block (`<!-- ledger:status:start/end -->`) the plan's
//!   "README block / STATUS.md becomes generated content" step embeds.
//!
//! Both are pure functions of a [`ComputeOutcome`]: no clock, no
//! randomness, entries already sorted by the engine — running twice, on
//! two machines, gives identical bytes (plan C1/M1.13; pinned by golden
//! and shuffled-input tests). The CI "STATUS is up to date" gate and the
//! remaining M1.9 renderers (`KNOWN_GAPS.md` generation, Astro page) are
//! later slices and deliberately absent here.

use std::fmt::Write as _;
use std::path::Path;

use ledger_schema::{Level, Tier};
use serde::Serialize;

use crate::compute::{ComputeOutcome, FeatureLevel, run_compute};

/// Schema tag of the status JSON contract.
pub const STATUS_SCHEMA: &str = "glyim.status/1";

/// Marker that opens the generated Markdown block (plan M1.9: generated
/// content is delimited so embedded updates never eat hand-written text).
pub const STATUS_MD_START: &str =
    "<!-- ledger:status:start (generated by `glyim-ledger status`; DO NOT EDIT) -->";

/// Marker that closes the generated Markdown block.
pub const STATUS_MD_END: &str = "<!-- ledger:status:end -->";

/// Result of a full `ledger status` run: the engine outcome the two
/// renderers consume.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct StatusOutcome {
    /// The underlying compute pass (entries, diagnostics, counts).
    pub compute: ComputeOutcome,
}

impl StatusOutcome {
    /// Number of error-severity diagnostics (delegates to the engine).
    #[must_use]
    pub fn errors(&self) -> usize {
        self.compute.errors()
    }

    /// True when no error-severity diagnostic was produced.
    #[must_use]
    pub fn is_ok(&self) -> bool {
        self.compute.is_ok()
    }
}

/// Runs a full `ledger status` pass: the M1.8 engine over `root`, ready
/// for both renderers. Same evidence contract as [`crate::run_compute`]
/// (`--evidence` override or `ledger/evidence/*.jsonl`).
#[must_use]
pub fn run_status(root: &Path, evidence: Option<&Path>) -> StatusOutcome {
    StatusOutcome {
        compute: run_compute(root, evidence),
    }
}

// -- renderers ---------------------------------------------------------------

/// Per-level feature counts in the JSON contract.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
struct LevelCounts {
    /// Features computed at L0 (declared only).
    #[serde(rename = "L0")]
    l0: usize,
    /// Features computed at L1 (parses).
    #[serde(rename = "L1")]
    l1: usize,
    /// Features computed at L2 (checks).
    #[serde(rename = "L2")]
    l2: usize,
    /// Features computed at L3 (interpreted).
    #[serde(rename = "L3")]
    l3: usize,
    /// Features computed at L4 (native-verified).
    #[serde(rename = "L4")]
    l4: usize,
    /// Features computed at L5 (hardened; unreachable today — see the
    /// compute module's unmeasured hardening axes).
    #[serde(rename = "L5")]
    l5: usize,
}

impl LevelCounts {
    fn histogram(entries: &[FeatureLevel]) -> Self {
        let mut counts = [0usize; 6];
        for entry in entries {
            counts[entry.computed_level as usize] += 1;
        }
        Self {
            l0: counts[0],
            l1: counts[1],
            l2: counts[2],
            l3: counts[3],
            l4: counts[4],
            l5: counts[5],
        }
    }
}

/// Per-feature summary entry in the JSON contract (the compute contract's
/// `missing`-reason prose is deliberately dropped here).
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
struct StatusEntry<'a> {
    /// Registry feature ID.
    id: &'a str,
    /// Maturity tier.
    tier: Tier,
    /// The level the registry demands.
    target_level: Level,
    /// The level the evidence supports after caps.
    computed_level: Level,
    /// Gap IDs that capped this feature.
    capped_by: &'a [String],
    /// Hardening axes with a threshold but no evidence source yet.
    unmeasured: &'a [&'static str],
}

/// JSON document rendered by [`format_status_json`].
#[derive(Serialize)]
struct StatusJson<'a> {
    schema: &'static str,
    features: usize,
    records: usize,
    summary: LevelCounts,
    entries: Vec<StatusEntry<'a>>,
}

/// Renders the `glyim.status/1` JSON contract (pretty-printed).
#[must_use]
pub fn format_status_json(outcome: &ComputeOutcome) -> String {
    let document = StatusJson {
        schema: STATUS_SCHEMA,
        features: outcome.features,
        records: outcome.records,
        summary: LevelCounts::histogram(&outcome.entries),
        entries: outcome
            .entries
            .iter()
            .map(|entry| StatusEntry {
                id: &entry.id,
                tier: entry.tier,
                target_level: entry.target_level,
                computed_level: entry.computed_level,
                capped_by: &entry.capped_by,
                unmeasured: &entry.unmeasured,
            })
            .collect(),
    };
    let mut text = serde_json::to_string_pretty(&document).unwrap_or_else(|err| {
        // Field sets are fixed and values are plain strings/numbers, so
        // serialization is infallible by construction; this arm keeps the
        // renderer total without introducing a Result into the format_*
        // family contract (same shape as `format_compute_json`).
        format!("{{\"schema\":\"{STATUS_SCHEMA}\",\"error\":\"{err}\"}}")
    });
    text.push('\n');
    text
}

/// Renders the marker-delimited Markdown status block.
///
/// Deterministic by construction: no clock, entries already sorted by the
/// engine, and the only variable content is the computed numbers — the
/// same `(registry, evidence, policy)` renders identical bytes anywhere
/// (plan C1/M1.13).
#[must_use]
pub fn format_status_markdown(outcome: &ComputeOutcome) -> String {
    let counts = LevelCounts::histogram(&outcome.entries);
    let histogram = [
        ("L0", counts.l0),
        ("L1", counts.l1),
        ("L2", counts.l2),
        ("L3", counts.l3),
        ("L4", counts.l4),
        ("L5", counts.l5),
    ];
    let mut text = String::new();
    text.push_str(STATUS_MD_START);
    text.push_str("\n\n# Readiness status\n\nComputed from the registry, `glyim.evidence/1` evidence, and `ledger/policy.toml`: **");
    let _ = write!(
        text,
        "{}** features over **{}** evidence record(s) ({} error(s), {} warning(s)).\n\n| Level | Features |\n|---|---|\n",
        outcome.features,
        outcome.records,
        outcome.errors(),
        outcome.warnings(),
    );
    for (spelling, count) in histogram {
        let _ = writeln!(text, "| {spelling} | {count} |");
    }
    text.push_str("\n| Feature | Tier | Target | Computed | Capped by | Unmeasured |\n|---|---|---|---|---|---|\n");
    for entry in &outcome.entries {
        let capped = if entry.capped_by.is_empty() {
            "-".to_string()
        } else {
            entry.capped_by.join(", ")
        };
        let unmeasured = if entry.unmeasured.is_empty() {
            "-".to_string()
        } else {
            entry.unmeasured.join(", ")
        };
        let _ = writeln!(
            text,
            "| `{}` | {} | {} | {} | {capped} | {unmeasured} |",
            entry.id,
            entry.tier.as_str(),
            entry.target_level.as_str(),
            entry.computed_level.as_str(),
        );
    }
    text.push('\n');
    text.push_str(STATUS_MD_END);
    text.push('\n');
    text
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::compute::ComputeOutcome;
    use ledger_schema::Diagnostic;

    /// A fixed engine outcome: two features, one capped, one unmeasured.
    fn sample() -> ComputeOutcome {
        ComputeOutcome {
            entries: vec![
                FeatureLevel {
                    id: "LANG-STATUS-A".to_string(),
                    tier: Tier::Core,
                    target_level: Level::L5,
                    computed_level: Level::L2,
                    capped_by: vec!["GAP-0001".to_string()],
                    unmeasured: vec![],
                    missing: vec![
                        "L3: 1 passed run-pass on gam required, 0 distinct seen".to_string(),
                    ],
                },
                FeatureLevel {
                    id: "LANG-STATUS-B".to_string(),
                    tier: Tier::Tooling,
                    target_level: Level::L5,
                    computed_level: Level::L4,
                    capped_by: vec![],
                    unmeasured: vec![
                        crate::compute::HARDENING_FUZZ_HOURS,
                        crate::compute::HARDENING_MUTATION_RATE,
                    ],
                    missing: vec![],
                },
            ],
            diagnostics: vec![Diagnostic {
                code: "LEDGER-WITNESS-DEBT",
                message: "gap GAP-0001 is unwitnessed (witness debt)".to_string(),
                severity: ledger_schema::Severity::Warning,
            }],
            features: 2,
            records: 7,
        }
    }

    // -- JSON contract -------------------------------------------------------

    #[test]
    fn golden_status_json_is_stable() {
        let expected = r#"{
  "schema": "glyim.status/1",
  "features": 2,
  "records": 7,
  "summary": {
    "L0": 0,
    "L1": 0,
    "L2": 1,
    "L3": 0,
    "L4": 1,
    "L5": 0
  },
  "entries": [
    {
      "id": "LANG-STATUS-A",
      "tier": "core",
      "target_level": "L5",
      "computed_level": "L2",
      "capped_by": [
        "GAP-0001"
      ],
      "unmeasured": []
    },
    {
      "id": "LANG-STATUS-B",
      "tier": "tooling",
      "target_level": "L5",
      "computed_level": "L4",
      "capped_by": [],
      "unmeasured": [
        "fuzz_cpu_hours",
        "mutation_kill_rate_pct"
      ]
    }
  ]
}
"#;
        assert_eq!(format_status_json(&sample()), expected);
    }

    #[test]
    fn status_json_summary_matches_entries() {
        let text = format_status_json(&sample());
        // Every entry is counted exactly once in the histogram: parse the
        // rendered JSON and cross-check the summary against the entries.
        let value: serde_json::Value = serde_json::from_str(&text).expect("valid JSON");
        assert_eq!(value["schema"], STATUS_SCHEMA);
        let summary = &value["summary"];
        let total: u64 = ["L0", "L1", "L2", "L3", "L4", "L5"]
            .iter()
            .map(|key| summary[key].as_u64().expect("count"))
            .sum();
        assert_eq!(total, 2);
        assert_eq!(summary["L2"], 1);
        assert_eq!(summary["L4"], 1);
        assert_eq!(value["entries"].as_array().map(Vec::len), Some(2));
    }

    // -- Markdown block -------------------------------------------------------

    #[test]
    fn golden_status_markdown_is_stable() {
        let expected = format!(
            "{STATUS_MD_START}\n\
             \n\
             # Readiness status\n\
             \n\
             Computed from the registry, `glyim.evidence/1` evidence, and \
             `ledger/policy.toml`: **2** features over **7** evidence record(s) \
             (0 error(s), 1 warning(s)).\n\
             \n\
             | Level | Features |\n\
             |---|---|\n\
             | L0 | 0 |\n\
             | L1 | 0 |\n\
             | L2 | 1 |\n\
             | L3 | 0 |\n\
             | L4 | 1 |\n\
             | L5 | 0 |\n\
             \n\
             | Feature | Tier | Target | Computed | Capped by | Unmeasured |\n\
             |---|---|---|---|---|---|\n\
             | `LANG-STATUS-A` | core | L5 | L2 | GAP-0001 | - |\n\
             | `LANG-STATUS-B` | tooling | L5 | L4 | - | fuzz_cpu_hours, mutation_kill_rate_pct |\n\
             \n\
             {STATUS_MD_END}\n"
        );
        assert_eq!(format_status_markdown(&sample()), expected);
    }

    #[test]
    fn status_markdown_is_marker_delimited() {
        let text = format_status_markdown(&sample());
        assert!(text.starts_with(STATUS_MD_START));
        assert!(text.ends_with(&(STATUS_MD_END.to_string() + "\n")));
        assert_eq!(text.matches(STATUS_MD_START).count(), 1);
        assert_eq!(text.matches(STATUS_MD_END).count(), 1);
    }

    // -- determinism ----------------------------------------------------------

    #[test]
    fn renderers_are_pure_and_repeatable() {
        let outcome = sample();
        assert_eq!(format_status_json(&outcome), format_status_json(&outcome));
        assert_eq!(
            format_status_markdown(&outcome),
            format_status_markdown(&outcome)
        );
        // Empty outcome renders an all-zero histogram, never a panic.
        let empty = ComputeOutcome {
            entries: Vec::new(),
            diagnostics: Vec::new(),
            features: 0,
            records: 0,
        };
        let text = format_status_json(&empty);
        assert!(text.contains("\"L0\": 0"), "{text}");
        let md = format_status_markdown(&empty);
        assert!(md.contains("| L0 | 0 |"), "{md}");
    }

    #[test]
    fn run_status_delegates_to_the_engine() {
        // A project without a policy fails through the same diagnostics
        // channel; the renderers still produce valid (all-zero) artifacts.
        let dir = tempfile::tempdir().expect("tmp");
        let outcome = run_status(dir.path(), None);
        assert!(!outcome.is_ok());
        assert_eq!(outcome.compute.entries.len(), 0);
        let text = format_status_json(&outcome.compute);
        assert!(text.contains("\"features\": 0"), "{text}");
    }
}
